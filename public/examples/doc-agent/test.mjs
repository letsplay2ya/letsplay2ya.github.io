import assert from 'node:assert/strict';
import {fileURLToPath} from 'node:url';
import {createTools,runAgent,baselineProvider,openAIProvider} from './agent.mjs';
const root=fileURLToPath(new URL('./fixtures/missing-script/',import.meta.url));
const host=await createTools(root);
await assert.rejects(()=>host.execute('read_file',{path:'../../.env'}),/allowed/);
await assert.rejects(()=>host.execute('read_file',{path:'C:/Windows/win.ini'}),/allowed/);
await assert.rejects(()=>host.execute('finish_report',{findings:[{path:'README.md',line:999,kind:'missing_file',explanation:'fabricated'}]}),/evidence/);
const baseline=await runAgent(baselineProvider(),root);
assert.equal(baseline.status,'complete');assert.equal(baseline.findings.length,1);
assert.equal(baseline.findings[0].kind,'missing_script');
const loop=await runAgent(async()=>({output:[{type:'function_call',call_id:'loop',name:'list_files',arguments:'{}'}]}),root,{maxTurns:2});
assert.equal(loop.status,'budget_exceeded');
const malformed=await runAgent(async()=>({output:[{type:'function_call',call_id:'bad',name:'read_file',arguments:'not json'}]}),root,{maxCalls:1});
assert.equal(malformed.status,'budget_exceeded');assert.ok(malformed.trace[0].result.error);
assert.throws(()=>openAIProvider({apiKey:'',model:'explicit-test-model'}),/required/);
let requests=0;const planner=baselineProvider();
const mockFetch=async(url,options)=>{
 assert.equal(url,'https://api.openai.com/v1/responses');
 assert.equal(options.headers.Authorization,'Bearer synthetic-test-key');
 const body=JSON.parse(options.body);assert.equal(body.store,false);assert.equal(body.model,'explicit-test-model');
 const last=body.input.at(-1);
 if(requests>0)assert.equal(last.type,'function_call_output');
 requests++;
 return {ok:true,json:()=>planner(body)};
};
const adapter=await runAgent(openAIProvider({apiKey:'synthetic-test-key',model:'explicit-test-model',fetchImpl:mockFetch}),root);
assert.equal(adapter.status,'complete');assert.equal(requests,4);
const failure=openAIProvider({apiKey:'synthetic-test-key',model:'explicit-test-model',fetchImpl:async()=>({ok:false,status:429})});
await assert.rejects(()=>failure({input:[],tools:[]}),/HTTP 429/);
const providerFailure=await runAgent(failure,root);
assert.equal(providerFailure.status,'provider_error');
assert.match(providerFailure.error,/HTTP 429/);
console.log('Agent checks passed: evidence, path boundary, turn/call budgets, malformed arguments, credential preflight, mocked Responses loop, API failure.');
