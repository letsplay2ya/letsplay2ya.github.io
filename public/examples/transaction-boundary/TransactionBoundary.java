import java.io.IOException;
import java.util.ArrayList;
import java.util.List;
import java.util.UUID;
import javax.sql.DataSource;
import org.springframework.aop.framework.ProxyFactory;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.jdbc.datasource.DriverManagerDataSource;
import org.springframework.transaction.PlatformTransactionManager;
import org.springframework.transaction.annotation.AnnotationTransactionAttributeSource;
import org.springframework.transaction.annotation.Transactional;
import org.springframework.transaction.interceptor.TransactionInterceptor;
import org.springframework.transaction.support.TransactionSynchronizationManager;

/** Standalone experiment: real Spring transaction advice and H2, no business application. */
public class TransactionBoundary {
    public interface Operations {
        void runtimeFailure();
        void checkedFailure() throws IOException;
        void checkedRollback() throws IOException;
        void catchInside();
        void selfInvocation();
        void outerTransaction();
        void catchOtherBean();
    }

    public static class Writer implements Operations {
        private final JdbcTemplate jdbc;
        private final List<Boolean> active;
        Operations other;

        Writer(JdbcTemplate jdbc, List<Boolean> active) {
            this.jdbc = jdbc;
            this.active = active;
        }
        private void insert() {
            active.add(TransactionSynchronizationManager.isActualTransactionActive());
            jdbc.update("insert into items(label) values (?)", "example");
        }
        @Transactional
        public void runtimeFailure() {
            insert();
            throw new IllegalStateException("simulated failure");
        }
        @Transactional
        public void checkedFailure() throws IOException {
            insert();
            throw new IOException("simulated checked failure");
        }
        @Transactional(rollbackFor = IOException.class)
        public void checkedRollback() throws IOException {
            insert();
            throw new IOException("simulated checked failure");
        }
        @Transactional
        public void catchInside() {
            try {
                insert();
                throw new IllegalStateException("caught before leaving method");
            } catch (IllegalStateException ignored) {
                // Advice sees a normal return; this code did not mark rollback-only.
            }
        }
        public void selfInvocation() {
            this.runtimeFailure();
        }
        @Transactional
        public void outerTransaction() {
            this.runtimeFailure();
        }
        @Transactional
        public void catchOtherBean() {
            try {
                other.runtimeFailure();
            } catch (IllegalStateException ignored) {
                // The other proxy has already marked the participating transaction rollback-only.
            }
        }
    }

    static Operations proxy(Writer target, PlatformTransactionManager manager) {
        var advice = new TransactionInterceptor();
        advice.setTransactionManager(manager);
        advice.setTransactionAttributeSource(new AnnotationTransactionAttributeSource());
        advice.afterPropertiesSet();
        var factory = new ProxyFactory();
        factory.setTarget(target);
        factory.setInterfaces(Operations.class);
        factory.addAdvice(advice);
        return (Operations) factory.getProxy();
    }

    @FunctionalInterface
    interface Call { void invoke(Operations proxied, Operations raw) throws Exception; }

    static String scenario(String name, Call call, int expectedRows, boolean expectedActive, String expectedError) {
        DataSource source = new DriverManagerDataSource("jdbc:h2:mem:" + UUID.randomUUID() + ";DB_CLOSE_DELAY=-1", "sa", "");
        var jdbc = new JdbcTemplate(source);
        jdbc.execute("create table items(id integer generated by default as identity primary key, label varchar(40))");
        var active = new ArrayList<Boolean>();
        var target = new Writer(jdbc, active);
        var manager = new DataSourceTransactionManager(source);
        var proxied = proxy(target, manager);
        target.other = proxy(new Writer(jdbc, active), manager);
        String error = "none";
        try {
            call.invoke(proxied, target);
        } catch (Exception failure) {
            error = failure.getClass().getSimpleName();
        }
        int rows = jdbc.queryForObject("select count(*) from items", Integer.class);
        if (rows != expectedRows || !active.equals(List.of(expectedActive)) || !error.equals(expectedError)) {
            throw new AssertionError(name + ": rows=" + rows + ", active=" + active + ", error=" + error);
        }
        jdbc.execute("shutdown");
        return "{\"case\":\"" + name + "\",\"transactionActive\":" + expectedActive
            + ",\"rowsAfterCall\":" + rows + ",\"error\":\"" + error + "\"}";
    }

    public static void main(String[] args) {
        var results = List.of(
            scenario("proxy-runtime", (p, raw) -> p.runtimeFailure(), 0, true, "IllegalStateException"),
            scenario("self-invocation", (p, raw) -> p.selfInvocation(), 1, false, "IllegalStateException"),
            scenario("raw-instance", (p, raw) -> raw.runtimeFailure(), 1, false, "IllegalStateException"),
            scenario("checked-default", (p, raw) -> p.checkedFailure(), 1, true, "IOException"),
            scenario("checked-rollback-for", (p, raw) -> p.checkedRollback(), 0, true, "IOException"),
            scenario("caught-inside", (p, raw) -> p.catchInside(), 1, true, "none"),
            scenario("self-with-outer-tx", (p, raw) -> p.outerTransaction(), 0, true, "IllegalStateException"),
            scenario("caught-other-required", (p, raw) -> p.catchOtherBean(), 0, true, "UnexpectedRollbackException")
        );
        System.out.println("[" + String.join(",", results) + "]");
    }
}
